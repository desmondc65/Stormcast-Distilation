def plot_all_variables(
    input_dir: pathlib.Path,
    output_dir: pathlib.Path,
    use_cartopy: bool = True,
    create_summary: bool = True,
) -> None:
    """Plot all variables from to_zarr.py output."""
    if not HAS_XARRAY:
        raise RuntimeError("xarray is required for plotting")
    if not HAS_MATPLOTLIB:
        raise RuntimeError("matplotlib is required for plotting")
    
    output_dir.mkdir(parents=True, exist_ok=True)
    
    print(f"Input directory: {input_dir}")
    print(f"Output directory: {output_dir}")
    print(f"Using Cartopy: {use_cartopy and HAS_CARTOPY}")
    
    # Plot LowRes
    lowres_store = input_dir / "LowRes" / "inference.zarr"
    lowres_output = output_dir / "LowRes"
    lowres_output.mkdir(parents=True, exist_ok=True)
    plot_zarr_store(lowres_store, lowres_output, "LowRes", "LowRes", use_cartopy)
    
    # Plot HighRes
    highres_store = input_dir / "HighRes" / "inference.zarr"
    highres_output = output_dir / "HighRes"
    highres_output.mkdir(parents=True, exist_ok=True)
    plot_zarr_store(highres_store, highres_output, "HighRes", "HighRes", use_cartopy)
    
    # Plot Invariants
    invariants_store = input_dir / "invariants" / "invariants.zarr"
    invariants_output = output_dir / "invariants"
    invariants_output.mkdir(parents=True, exist_ok=True)
    plot_invariants(invariants_store, invariants_output, use_cartopy)
    
    # Create summary plot
    if create_summary:
        create_summary_plot(input_dir, output_dir, use_cartopy)
    
    print(f"\nPlotting complete. Output saved to: {output_dir}")


