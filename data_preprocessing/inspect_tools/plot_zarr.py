def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Plot all variables from Zarr stores generated by to_zarr.py"
    )
    parser.add_argument(
        "input_dir",
        type=str,
        help="Path to the output directory from to_zarr.py (contains LowRes/, HighRes/, invariants/)",
    )
    parser.add_argument(
        "--output", "-o",
        type=str,
        default="./plots",
        help="Output directory for plot images (default: ./plots)",
    )
    parser.add_argument(
        "--no-cartopy",
        action="store_true",
        help="Disable Cartopy for map projections (use simple plots)",
    )
    parser.add_argument(
        "--no-summary",
        action="store_true",
        help="Skip creating summary plot",
    )
    return parser


def main():
    parser = build_parser()
    args = parser.parse_args()
    
    input_dir = pathlib.Path(args.input_dir)
    output_dir = pathlib.Path(args.output)
    
    if not input_dir.exists():
        print(f"Error: Input directory does not exist: {input_dir}")
        return 1
    
    use_cartopy = not args.no_cartopy
    create_summary = not args.no_summary
    
    plot_all_variables(input_dir, output_dir, use_cartopy, create_summary)
    return 0


if __name__ == "__main__":
    exit(main())
